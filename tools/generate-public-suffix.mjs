#!/usr/bin/env node
/**
 * Generate `src/public-suffix-data.ts` for `@sdkwork/deployments-pc-console-delivery`.
 *
 * WHY THIS EXISTS
 * ---------------
 * The service decides "is this a registrable root domain?" with
 * `psl::domain_str(...) != Some(host)` in
 * `crates/sdkwork-intelligence-deploy-service/src/domain_verification.rs`
 * (`normalize_zone_apex`). The console must reject the same inputs *before* the
 * round trip, so it needs the same Public Suffix List. Rather than re-typing a
 * curated subset by hand (which silently drifts from the service), this script
 * extracts the rules from the exact `psl` crate release the workspace locks in
 * `Cargo.lock` and freezes them into a committed module.
 *
 * HOW TO REGENERATE
 * -----------------
 *   pnpm --dir apps/sdkwork-deployments-pc exec node ../../tools/generate-public-suffix.mjs
 * or simply, from the repository root:
 *
 *   node tools/generate-public-suffix.mjs
 *
 * The script resolves the locked `psl` version from `Cargo.lock`, finds that
 * crate in the local cargo registry and reads `data/rules.txt`. Use
 * `--input <path>` to read an explicit rules file, or `--print` to only report
 * what would be written.
 *
 * The upstream list stores IDN rules in Unicode form only (`公司.cn`, `中国`) and
 * carries no `xn--` entries, yet the shipped crate matches punycode input: its
 * code generator (`psl-codegen`, run by cargo-make) emits both forms into
 * `src/list.rs`. Verified against the locked crate: `src/list.rs` contains the
 * label `中国` and an arm for `xn--fiqs8s`. Each non-ASCII rule is therefore also
 * emitted here in its punycode mirror image, which reproduces the same matching
 * behaviour on the client instead of inventing a different one.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const TARGET = join(
  REPO,
  "apps/sdkwork-deployments-pc/packages/sdkwork-deployments-pc-console-delivery/src/public-suffix-data.ts",
);

function argValue(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

/** Locked `psl` version, straight out of the workspace lock file. */
function lockedPslVersion() {
  const lock = readFileSync(join(REPO, "Cargo.lock"), "utf8");
  const match = /\[\[package\]\]\r?\nname = "psl"\r?\nversion = "([^"]+)"/.exec(lock);
  if (!match) throw new Error("Cargo.lock does not pin a `psl` package");
  return match[1];
}

/** Locate `psl-<version>/data/rules.txt` in the local cargo registry. */
function findRulesInRegistry(version) {
  const roots = [
    process.env.CARGO_HOME && join(process.env.CARGO_HOME, "registry", "src"),
    process.env.USERPROFILE && join(process.env.USERPROFILE, ".cargo", "registry", "src"),
    process.env.HOME && join(process.env.HOME, ".cargo", "registry", "src"),
  ].filter(Boolean);

  for (const root of roots) {
    if (!existsSync(root)) continue;
    for (const registry of readdirSync(root)) {
      const candidate = join(root, registry, `psl-${version}`, "data", "rules.txt");
      if (existsSync(candidate)) return candidate;
    }
  }
  throw new Error(
    `psl-${version}/data/rules.txt not found under the cargo registry. ` +
      `Run \`cargo fetch\` in this repository first, or pass --input <path>.`,
  );
}

/** Punycode mirror of a rule, preserving its `*.` / `!` marker. */
function toAsciiRule(rule) {
  const marker = rule.startsWith("*.") ? "*." : rule.startsWith("!") ? "!" : "";
  const body = rule.slice(marker.length);
  try {
    const { hostname } = new URL(`http://${body}`);
    return hostname === body ? undefined : `${marker}${hostname}`;
  } catch {
    return undefined;
  }
}

const version = lockedPslVersion();
const rulesPath = argValue("--input") ?? findRulesInRegistry(version);
const raw = readFileSync(rulesPath);

const rules = raw
  .toString("utf8")
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line.length > 0 && !line.startsWith("//"));

const asciiRules = [];
const mirrored = new Map();
for (const rule of rules) {
  if (/^[\x20-\x7e]*$/.test(rule)) {
    asciiRules.push(rule);
    continue;
  }
  const ascii = toAsciiRule(rule);
  if (ascii && !rules.includes(ascii)) mirrored.set(rule, ascii);
}

const unmirrored = [...mirrored.values()].sort();
const sha256 = createHash("sha256").update(raw).digest("hex");

const lines = [
  "// AUTO-GENERATED by tools/generate-public-suffix.mjs — do not edit by hand.",
  "//",
  `// Source: psl crate ${version} (Mozilla Public Suffix List, Unicode form), data/rules.txt`,
  `// rules.txt sha256: ${sha256}`,
  `// Rules: ${rules.length} (${asciiRules.length} ASCII, ${mirrored.size} IDN mirrored to punycode)`,
  "//",
  "// Regenerate with: node tools/generate-public-suffix.mjs",
  "",
  `export const PUBLIC_SUFFIX_SOURCE = "psl@${version}" as const;`,
  `export const PUBLIC_SUFFIX_SHA256 = "${sha256}" as const;`,
  `export const PUBLIC_SUFFIX_RULE_COUNT = ${rules.length};`,
  "",
  "/** Rules exactly as published upstream (ASCII plus Unicode IDN forms). */",
  "export const PUBLIC_SUFFIX_RULES = `",
  ...asciiRules,
  "`;",
  "",
  "/** Punycode mirror images of the 459-odd Unicode IDN rules. */",
  "export const PUBLIC_SUFFIX_ASCII_MIRRORS = `",
  ...unmirrored,
  "`;",
  "",
];

if (process.argv.includes("--print")) {
  process.stdout.write(lines.join("\n"));
  process.exit(0);
}

writeFileSync(TARGET, lines.join("\n"), "utf8");
process.stdout.write(
  `wrote ${TARGET}\n  psl ${version}\n  ${rules.length} rules (${asciiRules.length} ascii + ${mirrored.size} punycode mirrors)\n  sha256 ${sha256}\n`,
);
