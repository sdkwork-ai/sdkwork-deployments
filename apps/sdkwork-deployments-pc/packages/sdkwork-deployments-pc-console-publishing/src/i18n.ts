export type PublishingMessageKey = keyof typeof en;

export function publishingText(
  locale: DeploymentsLocale,
  key: PublishingMessageKey,
  values: Record<string, string | number> = {},
): string {
  const message = locale === "zh-CN" ? zh[key] : en[key];
  return Object.entries(values).reduce(
    (current, [name, value]) => current.replaceAll(`{${name}}`, String(value)),
    message,
  );
}

export type PublishingTranslator = (
  key: PublishingMessageKey,
  values?: Record<string, string | number>,
) => string;

export function publishingTranslator(locale: DeploymentsLocale): PublishingTranslator {
  return (key, values = {}) => publishingText(locale, key, values);
}

