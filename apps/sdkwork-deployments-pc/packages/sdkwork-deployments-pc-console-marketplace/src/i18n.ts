export function translateMarketplace(
  locale: DeploymentsLocale,
  key: MarketplaceMessageKey,
  values: Record<string, string | number> = {},
): string {
  const catalog = locale === "zh-CN" ? zhCn : enUs;
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    catalog[key],
  );
}

export function marketplaceTranslator(locale: DeploymentsLocale): (key: MarketplaceMessageKey, values?: Record<string, string | number>) => string {
  return (key, values) => translateMarketplace(locale, key, values);
}
